// celReserved are CEL's reserved words, which a rule cannot name a field by.
var celReserved = map[string]bool{"as": true, "break": true, "const": true, "continue": true, "else": true,
	"for": true, "function": true, "if": true, "import": true, "let": true, "loop": true, "package": true,
	"namespace": true, "return": true, "var": true, "in": true, "true": true, "false": true, "null": true}

// comment is a description as // lines.
func comment(desc string) string {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return ""
	}
	var out strings.Builder
	for _, para := range strings.Split(desc, "\n") {
		para = strings.TrimSpace(para)
		if para == "" {
			continue
		}
		line := "//"
		for _, w := range strings.Fields(para) {
			if len(line)+1+len(w) > 78 && line != "//" {
				out.WriteString(line + "\n")
				line = "//"
			}
			line += " " + w
		}
		out.WriteString(line + "\n")
	}
	return out.String()
}

// goType is the Go type of a schema; typeName names a struct it needs;
// path is the field's dotted JSON path in the spec ([] marks a list's
// items).
func (g *typeGen) goType(s *Schema, typeName, path string) string {
	if s.Ref != "" {
		ref := g.k.d.Schemas[s.Ref]
		if ref == nil {
			fatalf("%s: no schema %s", g.k.c.Kind, s.Ref)
		}
		name := g.k.c.Kind + s.Ref
		if g.status {
			name = g.k.c.Kind + "Observed" + s.Ref
		}
		if g.inStack[s.Ref] {
			g.usesJSON = true
			return "*apiextensionsv1.JSON"
		}
		if len(ref.Properties) == 0 && ref.AdditionalProperties == nil {
			g.usesJSON = true
			return "*apiextensionsv1.JSON"
		}
		if g.refPaths != nil {
			g.refPaths[name] = append(g.refPaths[name], path)
		}
		if _, done := g.defs[name]; !done {
			g.defs[name] = "" // reserve
			g.inStack[s.Ref] = true
			g.defs[name] = g.structDef(name, ref, false, path)
			g.order = append(g.order, name)
			delete(g.inStack, s.Ref)
		}
		return "*" + name
	}
	switch s.Type {
	case "string":
		if s.Format == "int64" || s.Format == "uint64" {
			if g.status {
				return "*string"
			}
			return "*int64"
		}
		return "*string"
	case "boolean":
		return "*bool"
	case "integer":
		if s.Format == "uint32" || s.Format == "int64" {
			return "*int64"
		}
		return "*int32"
	case "number":
		return "*float64"
	case "array":
		it := g.goType(s.Items, typeName+"Item", path+"[]")
		if strings.HasPrefix(it, "*") {
			it = it[1:]
		}
		if it == "apiextensionsv1.JSON" || strings.HasPrefix(it, "[]") {
			g.usesJSON = true
			return "[]apiextensionsv1.JSON"
		}
		return "[]" + it
	case "object":
		if s.AdditionalProperties != nil {
			if s.AdditionalProperties.Type == "string" && s.AdditionalProperties.Format == "" {
				return "map[string]string"
			}
			g.usesJSON = true
			return "map[string]apiextensionsv1.JSON"
		}
		if len(s.Properties) > 0 {
			name := typeName
			if _, done := g.defs[name]; !done {
				g.defs[name] = ""
				g.defs[name] = g.structDef(name, s, false, path)
				g.order = append(g.order, name)
			}
			return "*" + name
		}
	}
	g.usesJSON = true
	return "*apiextensionsv1.JSON"
}

// structDef writes a struct of a schema's fields: for the spec, the
// writable ones; for observedState, all of them. path is the struct's
// dotted JSON path in the spec ("" at the top).
func (g *typeGen) structDef(name string, s *Schema, top bool, path string) string {
	var b strings.Builder
	var rules []string
	fields := make([]string, 0, len(s.Properties))
	for f := range s.Properties {
		fields = append(fields, f)
	}
	sort.Strings(fields)
	for _, f := range fields {
		p := s.Properties[f]
		// The resource's own name is the object's (its ID and parents);
		// a nested name is data (an asset's bucket, a template's field).
		if !g.status && (isOutput(p) || (top && f == "name") || (g.k.insertStyle && f == "fingerprint")) {
			continue
		}
		fieldPath := f
		if path != "" {
			fieldPath = path + "." + f
		}
		if !g.status && g.k.c.Skip[fieldPath] != "" {
			if g.skipped != nil {
				g.skipped[fieldPath] = true
			}
			continue
		}
		t := g.goType(p, name+goName(f), fieldPath)
		secretField := !g.status && contains(g.k.c.Secrets, fieldPath)
		if secretField {
			if t != "*string" {
				fatalf("%s: secrets: %s is %s, not a string", g.k.c.Kind, fieldPath, t)
			}
			// Config Connector's shape for a secret string (SQLUser's
			// password): value, or valueFrom.secretKeyRef.
			t = "*secret.Legacy"
			g.secrets[fieldPath] = true
		}
		ref, isRef := g.refs[fieldPath]
		if g.status {
			isRef = false
		}
		refName := ""
		required := !g.status && strings.HasPrefix(strings.TrimSpace(p.Description), "Required.")
		if isRef {
			refName = refFieldName(f, ref.list)
			if celReserved[f] {
				fatalf("%s: refs: %s cannot be named in a CEL rule", g.k.c.Kind, fieldPath)
			}
			if required {
				rules = append(rules, fmt.Sprintf("// +kubebuilder:validation:XValidation:rule=\"has(self.%s) != has(self.%s)\",message=\"exactly one of %s and %s is required\"\n", f, refName, f, refName))
			} else {
				rules = append(rules, fmt.Sprintf("// +kubebuilder:validation:XValidation:rule=\"!(has(self.%s) && has(self.%s))\",message=\"set %s or %s, not both\"\n", f, refName, f, refName))
			}
			g.refApplied[fieldPath] = true
			g.usesRef = true
		}
		b.WriteString(comment(p.Description))
		if secretField {
			b.WriteString("//\n// Takes value, or valueFrom.secretKeyRef (name, key) of a Secret in the\n// object's namespace, which the controller reads and sends; the API never\n// returns it.\n")
		} else if !g.status && contains(g.k.c.InputOnly, fieldPath) {
			b.WriteString("//\n// The API never returns it: it is sent when the spec changes, and a\n// change made in the cloud is not seen.\n")
		}
		if len(p.Enum) > 0 && !g.status {
			b.WriteString("//\n// One of " + strings.Join(p.Enum, ", ") + ".\n")
		}
		immutable := top && (!g.k.updatable || strings.Contains(p.Description, "Immutable.") || contains(g.k.c.Immutable, f))
		if !g.status {
			if required && !isRef {
				b.WriteString("// +kubebuilder:validation:Required\n")
			} else {
				b.WriteString("// +optional\n")
			}
			if n := maxLength(p); n != "" {
				fmt.Fprintf(&b, "// +kubebuilder:validation:MaxLength=%s\n", n)
			}
			if immutable {
				fmt.Fprintf(&b, "// +kubebuilder:validation:XValidation:rule=\"self == oldSelf\",message=\"%s is immutable\"\n", f)
			}
		}
		if t == "*apiextensionsv1.JSON" || t == "map[string]apiextensionsv1.JSON" || t == "[]apiextensionsv1.JSON" {
			b.WriteString("// +kubebuilder:pruning:PreserveUnknownFields\n// +kubebuilder:validation:Schemaless\n")
			if t == "*apiextensionsv1.JSON" {
				b.WriteString("// +kubebuilder:validation:Type=object\n")
			}
		}
		fmt.Fprintf(&b, "%s %s `json:\"%s,omitempty\"`\n\n", goName(f), t, f)
		if isRef {
			if t != "*string" && t != "[]string" {
				fatalf("%s: refs: %s is %s, not a string or a list of strings", g.k.c.Kind, fieldPath, t)
			}
			b.WriteString(refComment(ref, f))
			b.WriteString("// +optional\n")
			if immutable {
				fmt.Fprintf(&b, "// +kubebuilder:validation:XValidation:rule=\"self == oldSelf\",message=\"%s is immutable\"\n", refName)
			}
			rt := "*commonv1alpha1.ResourceRef"
			if ref.list {
				rt = "[]commonv1alpha1.ResourceRef"
			}
			goRef := goName(f) + "Ref"
			if ref.list {
				goRef = goName(singularField(f)) + "Refs"
			}
			fmt.Fprintf(&b, "%s %s `json:\"%s,omitempty\"`\n\n", goRef, rt, refName)
		}
	}
	return strings.Join(rules, "") + fmt.Sprintf("type %s struct {\n", name) + b.String() + "}\n"
}

// checkSkips, after the spec is written: every nested Config.Skip path
// was left out, and a struct the Discovery document shares between
// paths ($ref) skips the same fields at each, since one Go type serves
// them all (it is written at the first path and reused at the others).
func (g *typeGen) checkSkips() error {
	// applied: p was left out, where its struct is written.
	applied := func(p string) bool {
		for range 16 {
			if g.skipped[p] {
				return true
			}
			moved := false
			for _, paths := range g.refPaths {
				for _, other := range paths[1:] {
					if rest, ok := strings.CutPrefix(p, other+"."); ok && other != paths[0] {
						p, moved = paths[0]+"."+rest, true
					}
				}
			}
			if !moved {
				return false
			}
		}
		return false
	}
	var errs []string
	for p := range g.k.c.Skip {
		if strings.ContainsAny(p, ".[") && !applied(p) {
			errs = append(errs, p+" is not a writable field of the spec")
		}
	}
	for _, paths := range g.refPaths {
		for _, other := range paths[1:] {
			for _, pair := range [][2]string{{paths[0], other}, {other, paths[0]}} {
				for p := range g.k.c.Skip {
					if rest, ok := strings.CutPrefix(p, pair[0]+"."); ok && g.k.c.Skip[pair[1]+"."+rest] == "" {
						errs = append(errs, fmt.Sprintf("%s is in a struct shared with %s: skip %s.%s too", p, pair[1], pair[1], rest))
					}
				}
			}
		}
	}
	if len(errs) == 0 {
		return nil
	}
	sort.Strings(errs)
	return fmt.Errorf("%s", strings.Join(slices.Compact(errs), "; "))
}

// checkRefs, after the spec is written: every Config.Refs path got its
// reference, and a struct the Discovery document shares between paths has
// the same references at each (one Go type serves them all).
func (g *typeGen) checkRefs() error {
	same := func(a, b builtRef) bool { return a.target == b.target && a.format == b.format && a.list == b.list }
	var errs []string
	for p, r := range g.refs {
		ok := g.refApplied[p]
		for _, paths := range g.refPaths {
			for _, other := range paths[1:] {
				if rest, found := strings.CutPrefix(p, other+"."); found {
					// Written where the shared struct is: at its first path.
					first, there := g.refs[paths[0]+"."+rest]
					ok = there && g.refApplied[paths[0]+"."+rest] && same(first, r)
				}
			}
			for _, other := range paths[1:] {
				if rest, found := strings.CutPrefix(p, paths[0]+"."); found {
					if o, there := g.refs[other+"."+rest]; !there || !same(o, r) {
						errs = append(errs, fmt.Sprintf("%s is in a struct shared with %s: name %s.%s in refs too, alike", p, other, other, rest))
					}
				}
			}
		}
		if !ok {
			errs = append(errs, p+" got no reference: not a string field the spec writes, or in a struct shared with another path")
		}
	}
	if len(errs) == 0 {
		return nil
	}
	sort.Strings(errs)
	return fmt.Errorf("%s", strings.Join(slices.Compact(errs), "; "))
}

