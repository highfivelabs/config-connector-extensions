// pluralName is the kind's lower-case plural, as controller-gen makes it.
func pluralName(kind string) string {
	l := strings.ToLower(kind)
	switch {
	case strings.HasSuffix(l, "y") && len(l) > 1 && !strings.ContainsAny(l[len(l)-2:len(l)-1], "aeiou"):
		return l[:len(l)-1] + "ies"
	case strings.HasSuffix(l, "s"), strings.HasSuffix(l, "x"), strings.HasSuffix(l, "ch"), strings.HasSuffix(l, "sh"):
		return l + "es"
	}
	return l + "s"
}

