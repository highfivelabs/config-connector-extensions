func sweepFile(kinds []*built) []byte {
	var b bytes.Buffer
	b.WriteString("# Generated by hack/discokind. Do not edit.\n")
	b.WriteString("# What hack/live/sweep.sh lists for the discokind kinds under a project:\n")
	b.WriteString("# kind, base URL, collection (location global or the kind's sweepLocation,\n# region us-central1, zone us-central1-a), the list answer's field,\n# soft-delete field=value.\n")
	sorted := append([]*built(nil), kinds...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].c.Kind < sorted[j].c.Kind })
	for _, k := range sorted {
		if k.sweep == "" {
			continue
		}
		coll, ok := k.sweep, true
		for _, p := range k.pathParams {
			v := map[string]string{"location": "global", "region": "us-central1", "zone": "us-central1-a"}[p]
			if p == "location" && k.c.SweepLocation != "" {
				v = k.c.SweepLocation
			}
			if v == "" {
				ok = false
			}
			coll = strings.Replace(coll, "{"+p+"}", v, 1)
		}
		if !ok {
			continue
		}
		soft := "-"
		if k.c.SoftDelete != nil {
			soft = k.c.SoftDelete.Field + "=" + k.c.SoftDelete.Value
		}
		field := coll[strings.LastIndex(coll, "/")+1:]
		if k.insertStyle {
			field = "items"
		}
		base := k.baseURL
		if loc := k.c.SweepLocation; k.c.LocationHost && loc != "" && loc != "global" {
			base = "https://" + loc + "-" + strings.TrimPrefix(base, "https://")
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%s\n", k.c.Kind, base, coll, field, soft)
	}
	return b.Bytes()
}

