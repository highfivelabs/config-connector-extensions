// typeGen writes Go struct types for Discovery schemas.
type typeGen struct {
	k        *built
	status   bool // observedState: int64 as strings, nothing required
	defs     map[string]string
	order    []string
	inStack  map[string]bool
	usesJSON bool
}

// comment is a description as // lines.
func comment(desc string) string {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return ""
	}
	var out strings.Builder
	for _, para := range strings.Split(desc, "\n") {
		para = strings.TrimSpace(para)
		if para == "" {
			continue
		}
		line := "//"
		for _, w := range strings.Fields(para) {
			if len(line)+1+len(w) > 78 && line != "//" {
				out.WriteString(line + "\n")
				line = "//"
			}
			line += " " + w
		}
		out.WriteString(line + "\n")
	}
	return out.String()
}

// goType is the Go type of a schema; typeName names a struct it needs.
func (g *typeGen) goType(s *Schema, typeName string) string {
	if s.Ref != "" {
		ref := g.k.d.Schemas[s.Ref]
		if ref == nil {
			fatalf("%s: no schema %s", g.k.c.Kind, s.Ref)
		}
		name := g.k.c.Kind + s.Ref
		if g.status {
			name = g.k.c.Kind + "Observed" + s.Ref
		}
		if g.inStack[s.Ref] {
			g.usesJSON = true
			return "*apiextensionsv1.JSON"
		}
		if len(ref.Properties) == 0 && ref.AdditionalProperties == nil {
			g.usesJSON = true
			return "*apiextensionsv1.JSON"
		}
		if _, done := g.defs[name]; !done {
			g.defs[name] = "" // reserve
			g.inStack[s.Ref] = true
			g.defs[name] = g.structDef(name, ref, false)
			g.order = append(g.order, name)
			delete(g.inStack, s.Ref)
		}
		return "*" + name
	}
	switch s.Type {
	case "string":
		if s.Format == "int64" || s.Format == "uint64" {
			if g.status {
				return "*string"
			}
			return "*int64"
		}
		return "*string"
	case "boolean":
		return "*bool"
	case "integer":
		if s.Format == "uint32" || s.Format == "int64" {
			return "*int64"
		}
		return "*int32"
	case "number":
		return "*float64"
	case "array":
		it := g.goType(s.Items, typeName+"Item")
		if strings.HasPrefix(it, "*") {
			it = it[1:]
		}
		if it == "apiextensionsv1.JSON" || strings.HasPrefix(it, "[]") {
			g.usesJSON = true
			return "[]apiextensionsv1.JSON"
		}
		return "[]" + it
	case "object":
		if s.AdditionalProperties != nil {
			if s.AdditionalProperties.Type == "string" && s.AdditionalProperties.Format == "" {
				return "map[string]string"
			}
			g.usesJSON = true
			return "map[string]apiextensionsv1.JSON"
		}
		if len(s.Properties) > 0 {
			name := typeName
			if _, done := g.defs[name]; !done {
				g.defs[name] = ""
				g.defs[name] = g.structDef(name, s, false)
				g.order = append(g.order, name)
			}
			return "*" + name
		}
	}
	g.usesJSON = true
	return "*apiextensionsv1.JSON"
}

// structDef writes a struct of a schema's fields: for the spec, the
// writable ones; for observedState, all of them.
func (g *typeGen) structDef(name string, s *Schema, top bool) string {
	var b strings.Builder
	fields := make([]string, 0, len(s.Properties))
	for f := range s.Properties {
		fields = append(fields, f)
	}
	sort.Strings(fields)
	fmt.Fprintf(&b, "type %s struct {\n", name)
	for _, f := range fields {
		p := s.Properties[f]
		// The resource's own name is the object's (its ID and parents);
		// a nested name is data (an asset's bucket, a template's field).
		if !g.status && (isOutput(p) || (top && f == "name") || (g.k.insertStyle && f == "fingerprint")) {
			continue
		}
		if top && g.k.c.Skip[f] != "" {
			continue
		}
		t := g.goType(p, name+goName(f))
		b.WriteString(comment(p.Description))
		if len(p.Enum) > 0 && !g.status {
			b.WriteString("//\n// One of " + strings.Join(p.Enum, ", ") + ".\n")
		}
		if !g.status {
			if strings.HasPrefix(strings.TrimSpace(p.Description), "Required.") {
				b.WriteString("// +kubebuilder:validation:Required\n")
			} else {
				b.WriteString("// +optional\n")
			}
			if n := maxLength(p); n != "" {
				fmt.Fprintf(&b, "// +kubebuilder:validation:MaxLength=%s\n", n)
			}
			if top && (!g.k.updatable || strings.Contains(p.Description, "Immutable.") || contains(g.k.c.Immutable, f)) {
				fmt.Fprintf(&b, "// +kubebuilder:validation:XValidation:rule=\"self == oldSelf\",message=\"%s is immutable\"\n", f)
			}
		}
		if t == "*apiextensionsv1.JSON" || t == "map[string]apiextensionsv1.JSON" || t == "[]apiextensionsv1.JSON" {
			b.WriteString("// +kubebuilder:pruning:PreserveUnknownFields\n// +kubebuilder:validation:Schemaless\n")
			if t == "*apiextensionsv1.JSON" {
				b.WriteString("// +kubebuilder:validation:Type=object\n")
			}
		}
		fmt.Fprintf(&b, "%s %s `json:\"%s,omitempty\"`\n\n", goName(f), t, f)
	}
	b.WriteString("}\n")
	return b.String()
}

