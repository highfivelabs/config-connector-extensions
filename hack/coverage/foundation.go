// foundation.md is the work queue for the kind agents: the gaps in the
// platform-foundation and security-adjacent categories, ranked. The ranking
// and the judgement (what to build, what upstream has, how big) are in
// foundation.yaml, by hand; the numbers (coverage of each item's resources,
// the attributes missing, the official kinds and their stability) are
// measured here, so the report stays true when the CRDs move.

//go:embed foundation.yaml
var foundationYAML []byte

type fItem struct {
	Title       string   `yaml:"title"`
	Importance  string   `yaml:"importance"` // A platform foundation, B security-adjacent and platform edge, C the rest
	Gap         string   `yaml:"gap"`        // whole, stability, field
	Modules     int      `yaml:"modules"`
	ModuleNames string   `yaml:"module_names"`
	Size        string   `yaml:"size"`      // S, M, L
	Resources   []string `yaml:"resources"` // "service/Resource" or "service/Resource:path[]"
	Missing     string   `yaml:"missing"`
	Attributes  string   `yaml:"attributes"`
	Upstream    string   `yaml:"upstream"`
	Build       string   `yaml:"build"`
	Decision    string   `yaml:"decision"`
	// Decided is the answer to Decision, with the design.md
	// decision that records it; it replaces the question.
	Decided string `yaml:"decided"`
}

type fFile struct {
	Items []fItem `yaml:"items"`
}

var (
	impRank = map[string]int{"A": 0, "B": 1, "C": 2}
	gapRank = map[string]int{"whole": 0, "stability": 1, "field": 2}
	szRank  = map[string]int{"S": 0, "M": 1, "L": 2}
)

type measured struct {
	attrs, off, beyond, uncovered int
	paths                         []string
	kinds                         []string
}

func measure(m *model, sel string) (measured, error) {
	id, prefix, _ := strings.Cut(sel, ":")
	var out measured
	for _, rows := range m.byHost {
		for _, rr := range rows {
			if rr.r.ID() != id {
				continue
			}
			seen := map[string]bool{}
			for _, mm := range rr.off {
				if !seen[mm.CRD.Kind] {
					seen[mm.CRD.Kind] = true
					k := mm.CRD.Kind
					if mm.CRD.Alpha {
						k += " (alpha)"
					}
					out.kinds = append(out.kinds, k)
				}
			}
			for _, mm := range rr.ours {
				if !seen["ours:"+mm.CRD.Kind] {
					seen["ours:"+mm.CRD.Kind] = true
					out.kinds = append(out.kinds, mm.CRD.Kind+" (ours)")
				}
			}
			for i, a := range rr.r.Attrs {
				if prefix != "" && !strings.HasPrefix(a.Path, prefix+".") {
					continue
				}
				out.attrs++
				_, o := rr.offPath[i]
				_, u := rr.ourPath[i]
				switch {
				case o:
					out.off++
				case u:
					out.beyond++
				default:
					out.uncovered++
					out.paths = append(out.paths, a.Path)
				}
			}
			sort.Strings(out.paths)
			return out, nil
		}
	}
	return out, fmt.Errorf("foundation.yaml names no resource %q", id)
}

func codeList(ps []string, max int) string {
	if len(ps) == 0 {
		return "none"
	}
	n := len(ps)
	if n > max {
		ps = ps[:max]
	}
	s := "`" + strings.Join(ps, "`, `") + "`"
	if n > max {
		s += fmt.Sprintf(" and %d more", n-max)
	}
	return s
}

func fpct(n, d int) string { return pct(n, d) + "%" }

func foundationReport(m *model, prio *Priority, catSums [4]counts, svcCat map[string]map[string]counts) (string, error) {
	var f fFile
	if err := yaml.Unmarshal(foundationYAML, &f); err != nil {
		return "", err
	}
	// The ranking is the file order; check it follows the stated rule.
	for i := 1; i < len(f.Items); i++ {
		a, b := f.Items[i-1], f.Items[i]
		ka := [4]int{impRank[a.Importance], gapRank[a.Gap], -a.Modules, szRank[a.Size]}
		kb := [4]int{impRank[b.Importance], gapRank[b.Gap], -b.Modules, szRank[b.Size]}
		for j := 0; j < 4; j++ {
			if ka[j] < kb[j] {
				break
			}
			if ka[j] > kb[j] {
				return "", fmt.Errorf("foundation.yaml: item %d (%q) ranks before item %d (%q): order is importance, then gap (whole, stability, field), then modules (most first), then size", i+1, b.Title, i, a.Title)
			}
		}
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# Foundation gap report\n\n")
	w("The work queue for the kind agents: what is missing from the platform foundation and the security-adjacent services, ranked. ")
	w("Everything up through a managed Kubernetes cluster is table stakes for a platform team establishing a target; security teams need what sits next to it; application primitives (Pub/Sub, Storage, Run, SQL, BigQuery) come after. ")
	w("The Cloud Foundation Fabric modules guide where effort goes (`catalog/docs/gcp-inventory.md`, v60.0.0).\n\n")
	w("Generated by `hack/coverage` from `hack/coverage/foundation.yaml` (the ranking and the judgement, by hand) and the coverage data (the numbers); do not edit. Read [README.md](README.md) first for what the numbers mean and how far to trust them.\n\n")

	w("## Where the foundation stands\n\n")
	w("By category, counted in attributes of the create requests of the resources in it ([README](README.md#tiers-and-categories)):\n\n")
	w("| Category | Resources | With an official kind | Attributes | Official | Ours beyond | Uncovered |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n")
	for i := 0; i < 2; i++ {
		c := catSums[i]
		w("| %s | %d | %d | %d | %s | %s | %s |\n", categoryNames[i], c.resources, c.resOff, c.attrs, fpct(c.off, c.attrs), fpct(c.beyond, c.attrs), fpct(c.uncovered, c.attrs))
	}
	w("\nBy service:\n\n| Category | Service | Resources | Attributes | Official | Ours beyond | Uncovered |\n| --- | --- | ---: | ---: | ---: | ---: | ---: |\n")
	for i := 0; i < 2; i++ {
		var hosts []string
		for h := range svcCat[categories[i]] {
			hosts = append(hosts, h)
		}
		sort.Slice(hosts, func(a, b int) bool {
			ca, cb := svcCat[categories[i]][hosts[a]], svcCat[categories[i]][hosts[b]]
			if ca.attrs != cb.attrs {
				return ca.attrs > cb.attrs
			}
			return hosts[a] < hosts[b]
		})
		for _, h := range hosts {
			c := svcCat[categories[i]][h]
			w("| %s | `%s` | %d | %d | %s | %s | %s |\n", catShort(categories[i]), h, c.resources, c.attrs, fpct(c.off, c.attrs), fpct(c.beyond, c.attrs), fpct(c.uncovered, c.attrs))
		}
	}
	w("\nWhat these numbers miss, for the foundation:\n\n")
	w("- **Kinds for operations that are not creates** (IAM policies and members, Shared VPC attachment, a project's metadata, Cloud NAT, routes of a router) are in no row's resource, but the kinds exist and their fields are counted against the parent they fill (`overrides.yaml`, `subresources`). Whole-resource gaps of that kind are in the queue below with `measured: n/a` where there is nothing to count against.\n")
	w("- **Alpha-only kinds count as official.** Several foundation kinds exist only as `v1alpha1`, which the charts refuse; they are listed under \"Official but alpha-only\".\n")
	w("- **Matching is by name.** Terraform-derived kinds that rename fields (Compute Engine, Kubernetes Engine) are undercounted by about 15%% of their fields.\n\n")

	w("## How the queue is ranked\n\n")
	w("1. **Importance.** A: platform foundation (organization, folders, projects, organization policy, IAM at every level, tags, contacts, Shared VPC, VPC networking, DNS, KMS, log sinks and buckets, a managed GKE cluster and Fleet). B: security-adjacent (Security Command Center, VPC Service Controls, Cloud Asset, audit, Binary Authorization, Secret Manager, CA, Armor). C: the rest.\n")
	w("2. **Kind of gap.** A whole resource (or a whole level of one) with no kind first, then a kind that exists only as alpha, then fields missing from a kind that exists.\n")
	w("3. **Module need**: how many Cloud Foundation Fabric modules create the resource (`catalog/docs/gcp-inventory.md`), most first.\n")
	w("4. **Size**: S (a field or a parent on an existing kind, or one small new kind), M (one or a few new kinds, or tens of fields), L (a large kind or many).\n\n")
	w("**Route.** A *whole* or *stability* gap is built here, in our API group, by the copy-upstream rule (`CONTRIBUTING.md`). A *field* gap on an official kind cannot be fixed here without a parallel kind of our own; `docs/design.md` decision 5 says to wait for the release unless a field is critical. Each field item says what upstream is doing, and the ones that need the builder to decide are marked **Decision**.\n\n")

	// The queue.
	w("## Queue\n\n")
	w("| # | Item | Imp. | Gap | Modules | Size | Measured: attributes uncovered / total (official) | Upstream |\n| ---: | --- | :-: | --- | ---: | :-: | --- | --- |\n")
	type resolved struct {
		it fItem
		ms []measured
	}
	var rs []resolved
	for _, it := range f.Items {
		r := resolved{it: it}
		for _, sel := range it.Resources {
			ms, err := measure(m, sel)
			if err != nil {
				return "", err
			}
			r.ms = append(r.ms, ms)
		}
		rs = append(rs, r)
	}
	short := func(s string) string {
		if i := strings.Index(s, ". "); i > 0 && i < 140 {
			return s[:i]
		}
		if len(s) > 140 {
			return s[:140] + "..."
		}
		return s
	}
	for i, r := range rs {
		var tot, off, unc int
		for _, ms := range r.ms {
			tot += ms.attrs
			off += ms.off
			unc += ms.uncovered
		}
		meas := "n/a (not a create, or not in the API's create requests)"
		if len(r.ms) > 0 {
			meas = fmt.Sprintf("%d / %d (%s)", unc, tot, fpct(off, tot))
		}
		w("| %d | [%s](#%d-%s) | %s | %s | %d | %s | %s | %s |\n", i+1, r.it.Title, i+1, anchor(r.it.Title), r.it.Importance, r.it.Gap, r.it.Modules, r.it.Size, meas, short(r.it.Upstream))
	}
	w("\n")

	for i, r := range rs {
		it := r.it
		w("### %d. %s\n\n", i+1, it.Title)
		w("- **Importance** %s, **gap** %s, **size** %s, **modules** %d (%s).\n", it.Importance, it.Gap, it.Size, it.Modules, it.ModuleNames)
		if len(it.Resources) > 0 {
			w("- **Measured** (resource: official / ours beyond / uncovered of attributes; official kinds):\n")
			for j, sel := range it.Resources {
				ms := r.ms[j]
				kinds := "no kind"
				if len(ms.kinds) > 0 {
					kinds = strings.Join(ms.kinds, ", ")
				}
				w("  - `%s`: %d / %d / %d of %d; %s\n", sel, ms.off, ms.beyond, ms.uncovered, ms.attrs, kinds)
			}
		}
		w("- **Missing, whole resources:** %s\n", strings.TrimSpace(it.Missing))
		w("- **Missing, attributes that matter:** %s\n", strings.TrimSpace(it.Attributes))
		for j, sel := range it.Resources {
			if ms := r.ms[j]; len(ms.paths) > 0 {
				w("  - uncovered in `%s` (measured): %s\n", sel, codeList(ms.paths, 10))
			}
		}
		w("- **Upstream** (Config Connector `master` at the pin and open pull requests, read 2026-11-09): %s\n", strings.TrimSpace(it.Upstream))
		w("- **Build:** %s\n", strings.TrimSpace(it.Build))
		if it.Decided != "" {
			w("- **Decided (2026-11-09):** %s\n", strings.TrimSpace(it.Decided))
		} else if it.Decision != "" {
			w("- **Decision (builder):** %s\n", strings.TrimSpace(it.Decision))
		}
		w("\n")
	}

	// Already built.
	w("## Already built here\n\n")
	w("Our kinds in the two categories, from the coverage data (the gaps above are what is left after them).\n\n")
	w("| Kind | Resource | Ours beyond official | From an open PR |\n| --- | --- | ---: | :-: |\n")
	var built [][]string
	for _, host := range m.hosts {
		for _, rr := range m.byHost[host] {
			c := prio.Category(host, rr.r.ID())
			if (c != "platform-foundation" && c != "security-adjacent") || len(rr.ours) == 0 {
				continue
			}
			var ks []string
			for _, mm := range rr.ours {
				ks = append(ks, mm.CRD.Kind)
			}
			built = append(built, []string{strings.Join(uniq(ks), ", "), rr.r.ID(), fmt.Sprint(rr.counts().beyond), b2s(rr.fromPR)})
		}
	}
	for _, u := range m.oursUnmap {
		built = append(built, []string{u.crd.Kind, "(not a create) " + u.reason, "n/a", "false"})
	}
	sort.Slice(built, func(i, j int) bool { return built[i][0] < built[j][0] })
	for _, r := range built {
		w("| %s | %s | %s | %s |\n", r[0], r[1], r[2], r[3])
	}

	// Alpha-only.
	w("\n## Official but alpha-only\n\n")
	w("Kinds Config Connector has only as `v1alpha1`, in the two categories. The charts refuse alpha kinds, so for a platform team these are gaps until they reach `v1beta1` upstream or we ship a stable kind (item with gap `stability`).\n\n")
	w("| Kind | Resource | Attributes official |\n| --- | --- | ---: |\n")
	var alpha [][]string
	seen := map[string]bool{}
	for _, host := range m.hosts {
		for _, rr := range m.byHost[host] {
			c := prio.Category(host, rr.r.ID())
			if c != "platform-foundation" && c != "security-adjacent" {
				continue
			}
			for _, mm := range rr.off {
				if mm.CRD.Alpha && !seen[mm.CRD.Kind+rr.r.ID()] {
					seen[mm.CRD.Kind+rr.r.ID()] = true
					n := 0
					for range mm.Covered {
						n++
					}
					alpha = append(alpha, []string{mm.CRD.Kind, rr.r.ID(), fmt.Sprint(n)})
				}
			}
		}
	}
	sort.Slice(alpha, func(i, j int) bool { return alpha[i][0] < alpha[j][0] })
	for _, r := range alpha {
		w("| %s | %s | %s |\n", r[0], r[1], r[2])
	}

	// Appendix.
	queue := map[string]int{}
	for i, r := range rs {
		for _, sel := range r.it.Resources {
			id, _, _ := strings.Cut(sel, ":")
			if _, ok := queue[id]; !ok {
				queue[id] = i + 1
			}
		}
	}
	w("\n## Every resource\n\n")
	w("<details><summary>All resources in the platform-foundation and security-adjacent categories, with the queue item that covers a gap (`-`: nothing to do, or not worth doing yet)</summary>\n\n")
	w("| Category | Resource | Official kinds | Ours | Attributes | Official | Ours beyond | Uncovered | Queue |\n| --- | --- | --- | --- | ---: | ---: | ---: | ---: | :-: |\n")
	for _, host := range m.hosts {
		for _, rr := range m.byHost[host] {
			c := prio.Category(host, rr.r.ID())
			if c != "platform-foundation" && c != "security-adjacent" {
				continue
			}
			var offk, oursk []string
			for _, mm := range rr.off {
				k := mm.CRD.Kind
				if mm.CRD.Alpha {
					k += " (alpha)"
				}
				offk = append(offk, k)
			}
			for _, mm := range rr.ours {
				oursk = append(oursk, mm.CRD.Kind)
			}
			ct := rr.counts()
			q := "-"
			if n, ok := queue[rr.r.ID()]; ok {
				q = fmt.Sprint(n)
			}
			w("| %s | `%s` | %s | %s | %d | %d | %d | %d | %s |\n", catShort(c), rr.r.ID(), orDash(strings.Join(uniq(offk), ", ")), orDash(strings.Join(uniq(oursk), ", ")), ct.attrs, ct.off, ct.beyond, ct.uncovered, q)
		}
	}
	w("\n</details>\n")
	return b.String(), nil
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func anchor(t string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(t) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case r == ' ' || r == '-':
			b.WriteRune('-')
		}
	}
	return b.String()
}
